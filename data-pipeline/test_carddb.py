def _sets(*rows):
    return [carddb.DbSet(i, name, None, tot) for i, (name, tot) in enumerate(rows, 1)]


def test_match_sets_spectralkitten_names(db):
    names = lambda series: [s.name for s in carddb.match_sets(series, db.sets)]
    assert names("Servant of the Betrayer") == ["Servants of the Betrayer"]
    assert names("The Dark Portal") == ["Through the Dark Portal"]
    assert names("Hunt for Illidan") == ["The Hunt for Illidan"]
    assert names("Heroes of Azeroth") == ["Heroes of Azeroth"]
    assert names("Player Crafted Item") == []


def test_match_sets_returns_all_sets_with_same_name(db):
    assert [s.id for s in carddb.match_sets("Alliance Hunter", db.sets)] == [4, 5]


def test_match_sets_prefers_exact_over_contains():
    sets = _sets(("Icecrown", 220), ("Assault on Icecrown Citadel", 93))
    assert [s.name for s in carddb.match_sets("Icecrown", sets)] == ["Icecrown"]


def test_match_sets_jaccard_threshold():
    sets = _sets(("Burning Crusade Collector's Edition Promos", 3), ("Wrath of the Lich King Collector's Edition Promos", 2))
    assert [s.name for s in carddb.match_sets("Burning Crusade Promo", sets)] == [sets[0].name]
    assert carddb.match_sets("Lich King Promo", sets) == []  # Jaccard 0.5 < 0.6


def test_pick_set_by_size_breaks_ties():
    sets = _sets(("Assault on Icecrown Citadel", 93), ("Assault on Icecrown Citadel Treasure", 30))
    cands = carddb.match_sets("Icecrown Citadel", sets)
    assert len(cands) == 2
    assert carddb.pick_set_by_size(cands, 30).name == "Assault on Icecrown Citadel Treasure"
    assert carddb.pick_set_by_size(cands, None) is None
    twins = _sets(("Alliance Hunter", 26), ("Alliance Hunter", 26))
    assert carddb.pick_set_by_size(twins, 26) is None


