def product(p, name, gid, gname, rarity="Common", img=True):
    return {"p": p, "n": name, "g": gid, "s": gname, "sc": None, "num": None, "r": rarity,
            "t": None, "img": f"https://img.example/{p}.jpg" if img else None,
            "u": f"https://www.tcgplayer.com/product/{p}"}


