def tcg_product(pid, name, rarity="Common"):
    return {"productId": pid, "name": name, "imageUrl": f"https://img.example/{pid}.jpg",
            "url": f"https://www.tcgplayer.com/product/{pid}",
            "extendedData": [{"name": "Rarity", "displayName": "Rarity", "value": rarity}]}


def _client():
    groups = [{"groupId": 100, "name": "Servants of the Betrayer", "abbreviation": None},
              {"groupId": 200, "name": "Mystery Box", "abbreviation": "MB"}]
    products = {100: [tcg_product(1001, "Hulok Trailblazer"), tcg_product(1002, "Hulok Trailblazer (LOOT)")],
                200: [tcg_product(2001, "Mystery Card")]}
    prices = {100: [dict(r, productId=1001) for r in PRICE_ROWS[:2]]}
    return FakeClient(groups, products, prices)


def test_run_writes_cards_v2_and_meta(tmp_path, db):
    out = tmp_path / "site" / "data"
    seen = []

    def images(products, generated_at):
        seen.extend(products)
        return {"generatedAt": generated_at, "hashes": {}}

    summary = bd.run(_client(), out_dir=out, site_dir=tmp_path / "site",
                     now=datetime(2026, 10, 26, 6, tzinfo=timezone.utc), images=images, card_db=db)
    cards = json.loads((out / "cards.json").read_text(encoding="utf-8"))
    assert cards["version"] == 2 and cards["generatedAt"] == "2026-10-26T06:00:00Z"
    assert {s["id"] for s in cards["sets"]} >= {48, 42}
    k = by_k(cards["cards"])
    assert k["48-163"]["p"] == 1001 and k["p1002"]["num"] == 163 and k["p2001"]["si"] is None

    prices = json.loads((out / "prices.json").read_text(encoding="utf-8"))
    assert set(prices["prices"]) == {"1001"}  # still keyed by productId

    meta = json.loads((out / "meta.json").read_text(encoding="utf-8"))
    assert meta["cardsVersion"] == 2 and meta["productCount"] == 3
    assert meta["link"]["linked"] == 2 and meta["link"]["tcgProducts"] == 3 and meta["link"]["unlinked"] == 1
    commits = {s.get("commit") for s in meta["sources"]}
    assert {carddb.CARDDB_COMMIT, carddb.SK_COMMIT} <= commits
    assert meta["cardCount"] == len(cards["cards"]) == summary["cards"]

    assert [p["p"] for p in seen] == [1001, 1002, 2001]  # image hashes still per TCGplayer product
    assert "SpectralKitten" in (tmp_path / "site" / "index.html").read_text(encoding="utf-8")


