#!/usr/bin/env python3
"""Generate the built-in fallback TLS certificate for the firmware.

Creates a self-signed EC P-256 certificate and key (10 years) and writes
firmware/include/default_cert.h with both PEM strings in PROGMEM. The firmware
uses this pair only when no /cert.pem and /key.pem exist in LittleFS. The
header is generated, never committed (see firmware/.gitignore).

Uses the `cryptography` package. If it is not installed, falls back to the
openssl CLI (1.1.1 or newer).

Usage: python3 tools/make_default_cert.py
"""

from __future__ import annotations

import datetime
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "firmware" / "include" / "default_cert.h"

COMMON_NAME = "wowscanner"
DNS_NAMES = ["wowscanner.local", "wowscanner"]
VALID_DAYS = 3650


def generate_with_cryptography() -> tuple[str, str]:
    """Return (certificate PEM, private key PEM) using the cryptography package."""
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, COMMON_NAME)])
    now = datetime.datetime.now(datetime.timezone.utc)

    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(minutes=5))
        .not_valid_after(now + datetime.timedelta(days=VALID_DAYS))
        .add_extension(
            x509.SubjectAlternativeName([x509.DNSName(n) for n in DNS_NAMES]),
            critical=False,
        )
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=False,
                crl_sign=False,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(
            x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False
        )
        .sign(key, hashes.SHA256())
    )

    cert_pem = cert.public_bytes(serialization.Encoding.PEM).decode("ascii")
    key_pem = key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.TraditionalOpenSSL,  # "EC PRIVATE KEY" (SEC1)
        serialization.NoEncryption(),
    ).decode("ascii")
    return cert_pem, key_pem


def generate_with_openssl() -> tuple[str, str]:
    """Fallback path: produce the same pair with the openssl CLI."""
    san = "subjectAltName=" + ",".join("DNS:" + n for n in DNS_NAMES)
    with tempfile.TemporaryDirectory() as tmp:
        key_path = Path(tmp) / "key.pem"
        cert_path = Path(tmp) / "cert.pem"
        subprocess.run(
            ["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout",
             "-out", str(key_path)],
            check=True,
        )
        subprocess.run(
            [
                "openssl", "req", "-new", "-x509", "-sha256",
                "-key", str(key_path), "-out", str(cert_path),
                "-days", str(VALID_DAYS),
                "-subj", "/CN=" + COMMON_NAME,
                "-addext", san,
                "-addext", "basicConstraints=critical,CA:FALSE",
                "-addext", "keyUsage=critical,digitalSignature",
                "-addext", "extendedKeyUsage=serverAuth",
            ],
            check=True,
        )
        return cert_path.read_text(encoding="ascii"), key_path.read_text(encoding="ascii")


def generate() -> tuple[str, str]:
    try:
        import cryptography  # noqa: F401
    except ImportError:
        print("make_default_cert: 'cryptography' not installed, using openssl CLI")
        return generate_with_openssl()
    return generate_with_cryptography()


def pem_to_c_literal(name: str, pem: str) -> str:
    lines = [line for line in pem.strip().splitlines() if line]
    body = "\n".join('    "%s\\n"' % line for line in lines)
    return "static const char %s[] PROGMEM =\n%s;\n" % (name, body)


def render_header(cert_pem: str, key_pem: str) -> str:
    return (
        "// AUTO-GENERATED by tools/make_default_cert.py -- do not edit.\n"
        "// Built-in self-signed EC P-256 certificate (fallback when LittleFS has none).\n"
        "// Do not commit this file; regenerate it instead.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        + pem_to_c_literal("DEFAULT_CERT_PEM", cert_pem)
        + "\n"
        + pem_to_c_literal("DEFAULT_KEY_PEM", key_pem)
    )


def main() -> int:
    try:
        cert_pem, key_pem = generate()
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        print("make_default_cert: certificate generation failed: %s" % exc, file=sys.stderr)
        print("Install 'cryptography' (pip install cryptography) or openssl.", file=sys.stderr)
        return 1

    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(render_header(cert_pem, key_pem), encoding="utf-8", newline="\n")
    print("make_default_cert: wrote %s" % HEADER.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
