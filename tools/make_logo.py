#!/usr/bin/env python3
"""Draw the 128x64 splash logo for the OLED.

The artwork is original (a trading card, a magnifier and a coin); it uses no
third-party logos or game assets.

Outputs:
  firmware/include/logo.h      PROGMEM byte array in XBM bit order
                               (bit 0 = leftmost pixel of each byte), usable
                               with U8g2 drawXBMP().
  firmware/logo_preview.png    Upscaled preview for review.

Requires Pillow: pip install pillow
Usage: python3 tools/make_logo.py
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "firmware" / "include" / "logo.h"
PREVIEW = ROOT / "firmware" / "logo_preview.png"

WIDTH = 128
HEIGHT = 64
LIT = 1  # a set pixel is lit on the OLED
PREVIEW_SCALE = 3


def draw_logo() -> Image.Image:
    """Compose the logo. Artwork stays above y=47 so the splash text fits below it."""
    img = Image.new("1", (WIDTH, HEIGHT), 0)
    d = ImageDraw.Draw(img)

    # Back card: outline only, offset to the upper left.
    d.rounded_rectangle((10, 6, 50, 44), radius=4, outline=LIT, width=2)

    # Front card: solid border with a dark art panel and a name bar.
    d.rounded_rectangle((22, 2, 64, 46), radius=4, fill=LIT)
    d.rounded_rectangle((26, 6, 60, 42), radius=2, fill=0)
    d.rectangle((30, 9, 56, 11), fill=LIT)          # name bar
    d.rectangle((30, 37, 44, 39), fill=LIT)         # number bar
    gem = [(43, 15), (53, 24), (43, 34), (33, 24)]  # gem in the art window
    d.polygon(gem, fill=LIT)
    d.polygon([(43, 19), (48, 24), (43, 29), (38, 24)], fill=0)

    # Magnifier, lens top right, handle pointing toward the coin.
    d.ellipse((74, 2, 102, 30), outline=LIT, width=3)
    d.line((96, 24, 110, 38), fill=LIT, width=4)

    # Coin under the lens: double ring with a centre disc.
    d.ellipse((92, 30, 110, 46), outline=LIT, width=2)
    d.ellipse((97, 35, 105, 41), fill=LIT)

    return img


def pack_xbm(img: Image.Image) -> list[int]:
    """Pack rows into bytes, least significant bit = leftmost pixel."""
    pixels = img.load()
    data = []
    for y in range(HEIGHT):
        for x0 in range(0, WIDTH, 8):
            value = 0
            for bit in range(8):
                if pixels[x0 + bit, y]:
                    value |= 1 << bit
            data.append(value)
    return data


def render_header(data: list[int]) -> str:
    rows = []
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        rows.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    return (
        "// AUTO-GENERATED by tools/make_logo.py -- do not edit.\n"
        "// 128x64 monochrome splash logo (original artwork).\n"
        "// Bit order is XBM: bit 0 of each byte is the leftmost pixel.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        "#define LOGO_WIDTH 128\n"
        "#define LOGO_HEIGHT 64\n\n"
        "static const uint8_t LOGO_BITS[] PROGMEM = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def write_if_changed(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    img = draw_logo()
    data = pack_xbm(img)
    changed = write_if_changed(HEADER, render_header(data))

    preview = img.convert("L").resize(
        (WIDTH * PREVIEW_SCALE, HEIGHT * PREVIEW_SCALE), Image.NEAREST
    )
    PREVIEW.parent.mkdir(parents=True, exist_ok=True)
    preview.save(PREVIEW, format="PNG")

    print(
        "make_logo: %s (%s), preview %s"
        % (HEADER.relative_to(ROOT), "updated" if changed else "unchanged",
           PREVIEW.relative_to(ROOT))
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
