#!/usr/bin/env python3
"""Embed the web app into the firmware.

Reads webapp/index.html, webapp/app.js and webapp/style.css, gzips every file
and writes firmware/include/web_assets.h: one PROGMEM byte array per file, its
length, and a table that maps served paths to MIME types.

A missing source file is replaced by a small placeholder, so the firmware
still builds before the web app exists.

Usage: python3 tools/embed_web.py
"""

from __future__ import annotations

import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEBAPP_DIR = ROOT / "webapp"
OUTPUT = ROOT / "firmware" / "include" / "web_assets.h"

# (source file, served paths, MIME type, C identifier stem)
ASSETS = [
    ("index.html", ("/", "/index.html"), "text/html; charset=utf-8", "WEB_INDEX_HTML"),
    ("app.js", ("/app.js",), "application/javascript; charset=utf-8", "WEB_APP_JS"),
    ("style.css", ("/style.css",), "text/css; charset=utf-8", "WEB_STYLE_CSS"),
]

PLACEHOLDERS = {
    "index.html": (
        "<!doctype html>\n"
        '<html lang="de"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        "<title>WoW Scanner</title></head>\n"
        "<body><h1>Web-App fehlt</h1>\n"
        "<p>Diese Firmware wurde ohne webapp/ gebaut. Bitte tools/embed_web.py "
        "mit vorhandenem webapp/ ausf&uuml;hren.</p>\n"
        "</body></html>\n"
    ),
    "app.js": "// placeholder: webapp/app.js was not available at build time\n",
    "style.css": "/* placeholder: webapp/style.css was not available at build time */\n",
}

# Soft budget from SPEC section 2: all three files together gzip to < 40 KB.
SIZE_BUDGET = 40 * 1024


def load_gzipped(name: str) -> tuple[bytes, str]:
    """Return (gzip bytes, source description) for one webapp file."""
    path = WEBAPP_DIR / name
    if path.is_file():
        raw = path.read_bytes()
        source = str(path.relative_to(ROOT))
    else:
        raw = PLACEHOLDERS[name].encode("utf-8")
        source = "placeholder (webapp/%s fehlt)" % name
    # mtime=0 keeps the output reproducible across builds.
    return gzip.compress(raw, compresslevel=9, mtime=0), source


def c_byte_array(identifier: str, data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        rows.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    return (
        "static const uint8_t %s_GZ[] PROGMEM = {\n%s\n};\n"
        "static const size_t %s_GZ_LEN = %d;\n\n"
        % (identifier, "\n".join(rows), identifier, len(data))
    )


def render_header() -> tuple[str, int]:
    """Build the complete header text. Returns (text, total gzip bytes)."""
    parts = [
        "// AUTO-GENERATED by tools/embed_web.py from webapp/ -- do not edit.\n",
        "// Gzip-compressed web app assets, served with Content-Encoding: gzip.\n",
        "#pragma once\n",
        "#include <Arduino.h>\n\n",
    ]
    table_rows = []
    total = 0
    for source, paths, mime, identifier in ASSETS:
        blob, description = load_gzipped(source)
        total += len(blob)
        parts.append("// source: %s\n" % description)
        parts.append(c_byte_array(identifier, blob))
        for served in paths:
            table_rows.append(
                '    { "%s", "%s", %s_GZ, %s_GZ_LEN },\n'
                % (served, mime, identifier, identifier)
            )

    parts.append("struct WebAsset {\n")
    parts.append("    const char* path;\n")
    parts.append("    const char* mime;\n")
    parts.append("    const uint8_t* data;\n")
    parts.append("    size_t length;\n")
    parts.append("};\n\n")
    parts.append("static const WebAsset WEB_ASSETS[] = {\n")
    parts.extend(table_rows)
    parts.append("};\n")
    parts.append(
        "static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);\n"
    )
    return "".join(parts), total


def write_if_changed(path: Path, text: str) -> bool:
    """Write the file only when its content differs, so builds stay incremental."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    text, total = render_header()
    changed = write_if_changed(OUTPUT, text)
    print(
        "embed_web: %s (%s), gzip total %d bytes%s"
        % (
            OUTPUT.relative_to(ROOT),
            "updated" if changed else "unchanged",
            total,
            "" if total < SIZE_BUDGET else "  WARNING: exceeds 40 KB budget",
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
